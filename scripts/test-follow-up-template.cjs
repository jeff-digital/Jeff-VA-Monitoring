const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source=fs.readFileSync('src/frontend/js/modules/04-gmail.js','utf8');
const start=source.indexOf('  const DOCUMENT_TEMPLATE_DEFINITIONS =');
const end=source.indexOf('  };',start)+5;
const context=vm.createContext({ contractDuration: () => '', Intl });
vm.runInContext(source.slice(start,end)+'\n'+source.slice(source.indexOf('  function buildDocumentEmailTemplate('),source.indexOf('  function renderEmailTemplateOptions(')),context);
const app={ clientName:'Acme', contact:'Jordan', role:'Graphic Designer', platform:'OnlineJobs.ph', appliedDate:'2026-10-21' };
const template=context.buildDocumentEmailTemplate('follow-up',app);
assert.equal(template.subject,'Graphic Designer');
assert.match(template.body,/Hi Jordan/);
assert.match(template.body,/Oct 21, 2026 through OnlineJobs\.ph/);
assert.doesNotMatch(template.subject+template.body,/{{/);
assert.equal(context.buildDocumentEmailTemplate('follow-up',{...app,platform:''}).subject,'Graphic Designer');
assert.equal(context.buildDocumentEmailTemplate('follow-up',{...app,platform:'Direct client'}).subject,'Graphic Designer');
assert.doesNotMatch(context.buildDocumentEmailTemplate('follow-up',{}).body,/Invalid|{{/);
assert.doesNotMatch(context.buildDocumentEmailTemplate('follow-up',{...app, platform:''}).body,/ through /);
assert.match(context.buildDocumentEmailTemplate('follow-up',{...app, platform:'Direct client'}).body,/directly with your company/);
assert.equal(context.buildDocumentEmailTemplate('proceed-application',app).subject,'Application for - Graphic Designer');
const nodes = { '#documentTemplateSelect': { value: 'follow-up' }, '#documentTemplatePreview': {} };
context.$ = selector => nodes[selector];
context.escapeHtml = value => String(value).replaceAll('<','&lt;');
context.htmlEmailBodyFromText = value => value;
const tools=fs.readFileSync('src/frontend/js/modules/pages/11-tools-page.js','utf8');
vm.runInContext(tools.slice(tools.indexOf('  function renderTemplateTesterPreview('),tools.indexOf("  $('#personalDocumentInput')")),context);
context.renderTemplateTesterPreview();
const preview=nodes['#documentTemplatePreview'].innerHTML;
assert.match(preview,/Subject<\/span><strong>Social Media Management Services<\/strong>/);
assert.match(preview,/Oct 21, 2026 through OnlineJobs\.ph/);
assert.doesNotMatch(preview,/{{/);
console.log('Follow-up templates passed: role-only subject and platform in message, missing platform, personalized contact/date, no unresolved placeholders, application template unchanged.');
