const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { readModules, moduleGroups } = require('./lib/read-modules.cjs');
const read = file => moduleGroups[file] ? readModules(moduleGroups[file]) : fs.readFileSync(path.join(__dirname, '../src/frontend/js/modules', file), 'utf8');
const nodes = new Map();
const $ = key => { if (!nodes.has(key)) nodes.set(key, { value: '', textContent: '', innerHTML: '', hidden: false }); return nodes.get(key); };
const context = vm.createContext({ $, applicationDateSort: 'all', applicationDateFilter: '2026-10-21',
  escapeHtml: value => String(value), emailDate: value => value, view: 'applications' });
const matcher = read('02-email-matching.js');
const defaultsStart = matcher.indexOf("    if (view === 'applications') {", matcher.indexOf('  function showView('));
const defaultsEnd = matcher.indexOf("    if (view === 'hired')", defaultsStart);
assert.ok(defaultsStart >= 0 && defaultsEnd > defaultsStart);
const defaults = matcher.slice(defaultsStart, defaultsEnd);
$('#statusFilter').value = 'Interview';
vm.runInContext(defaults, context);
assert.equal(context.applicationDateSort, '0');
assert.equal(context.applicationDateFilter, '');
assert.equal($('#applicationDateSort').value, '0');
assert.equal($('#applicationDateFilter').value, '');
assert.equal($('#statusFilter').value, 'Applied');
const start = matcher.indexOf('    const filterChips = [');
const end = matcher.indexOf("    $$('[data-application-view]')", start);
assert.ok(start >= 0 && end > start);
vm.runInContext(`function renderApplications() {
  const query = $('#applicationSearch').value, dateFilter = applicationDateFilter;
  const status = $('#statusFilter').value, platform = $('#platformFilter').value;
  ${matcher.slice(start, end)}
}`, context);
context.renderApplications();
assert.equal($('#applicationFilterChips').innerHTML, '', 'Defaults do not add clickable chips');
$('#statusFilter').value = 'Interview'; $('#applicationSearch').value = 'Acme';
context.renderApplications();
assert.match($('#applicationFilterChips').innerHTML, /Stage: Interview/);
assert.match($('#applicationFilterChips').innerHTML, /Search: Acme/);
context.applicationDateSort = 'all';
vm.runInContext(defaults, context);
assert.equal(context.applicationDateSort, '0', 'Returning to Applications restores This week');
assert.equal($('#statusFilter').value, 'Applied', 'Returning restores Applied');
const html = fs.readFileSync(path.join(__dirname, '../src/frontend/index.html'), 'utf8');
assert.ok(!html.includes('data-application-quick-filter'));
assert.ok(!read('pages/07-applications-page.js').includes('data-application-quick-filter'));
console.log('Applications default to This week and Applied on entry, without clickable quick filters; other filters remain available.');
