import assert from 'node:assert/strict';
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
const { PGlite } = await import(process.env.PGLITE_MODULE ? pathToFileURL(process.env.PGLITE_MODULE).href : '@electric-sql/pglite');
const db = new PGlite();
const owner = '11111111-1111-4111-8111-111111111111', other = '22222222-2222-4222-8222-222222222222';
try {
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;
    create table public.app_state(user_id uuid primary key,data jsonb not null default '{}',updated_at timestamptz default now());
    grant select,insert,update,delete on public.app_state to authenticated;
    alter table public.app_state enable row level security;
    create policy own_records on public.app_state for all to authenticated using (auth.uid()=user_id) with check (auth.uid()=user_id);`);
  const migration = fs.readFileSync(new URL('../src/backend/supabase/workspace-page-storage-migration.sql', import.meta.url), 'utf8');
  await db.exec(migration); await db.exec(migration);
  const first = { id: 'a', title: 'Original A' }, second = { id: 'b', title: 'Original B' };
  const original = { applications: [first, second], emails: [{ id: 'email', body: 'large-private-message'.repeat(10000) }], customLegacyField: { keep: true } };
  await db.query('insert into public.app_state(user_id,data) values($1,$2),($3,$2)', [owner, original, other]);
  const claim = async id => { await db.exec('reset role; set role authenticated'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]); };
  const save = async changes => (await db.query('select public.apply_workspace_changes($1) as result', [JSON.stringify(changes)])).rows[0].result;
  const read = async () => (await db.query('select data from public.app_state')).rows;
  await claim(owner);
  const editA = { key: 'applications', type: 'put', id: 'a', base: first, value: { ...first, title: 'Edited A' } };
  let result = await save([editA]);
  assert.equal(result.saved, true);
  assert.ok(JSON.stringify(result).length < 200, 'Saves return only a small acknowledgement, not the workspace');
  await save([{ key: 'applications', type: 'put', id: 'b', base: second, value: { ...second, title: 'Edited B' } }]);
  let data = (await read())[0].data;
  assert.deepEqual(data.applications.map(item => item.title), ['Edited A', 'Edited B'], 'Independent device edits merge by record');
  assert.equal(data.emails[0].body, original.emails[0].body);
  assert.equal((await db.query("select public.get_workspace_record('applications','a') as record")).rows[0].record.title, 'Edited A');
  assert.deepEqual(data.customLegacyField, original.customLegacyField);
  await save([editA]); // Idempotent replay after a lost response.
  await assert.rejects(save([{ ...editA, value: { id: 'a', title: 'Stale overwrite' } }]), error => error.code === '40001');
  await assert.rejects(save([{ key: 'dailyTasks', type: 'put', id: 'task', base: null, value: { id: 'task' } }, { ...editA, value: { id: 'a', title: 'Conflict' } }]), error => error.code === '40001');
  assert.equal((await read())[0].data.dailyTasks, undefined, 'A conflicting batch rolls back every change');
  await save([{ key: 'applications', type: 'put', id: 'new', base: null, value: { id: 'new' }, beforeId: 'a' }]);
  assert.deepEqual((await read())[0].data.applications.map(item => item.id), ['new','a','b']);
  await save([{ key: 'applications', type: 'remove', id: 'new', base: { id: 'new' } }]);
  await save([{ key: 'applications', type: 'remove', id: 'new', base: { id: 'new' } }]);
  assert.deepEqual((await read())[0].data.applications.map(item => item.id), ['a','b']);
  await save([{ key: 'applications', type: 'order', base: ['a','b'], value: ['b','a'] }]);
  assert.deepEqual((await read())[0].data.applications.map(item => item.id), ['b','a']);
  await save([{ key: 'applications', type: 'put', id: 'remote', base: null, value: { id: 'remote' } }]);
  await save([{ key: 'applications', type: 'order', base: ['b','a'], value: ['a','b'] }]);
  assert.deepEqual((await read())[0].data.applications.map(item => item.id), ['a','b','remote'], 'Reordering keeps records added by another device');
  await save([{ key: 'weeklyActivityGoal', type: 'set', base: null, value: 15 }]);
  assert.equal((await read())[0].data.weeklyActivityGoal, 15);
  await assert.rejects(save([{ key: 'user_id', type: 'set', base: null, value: other }]));
  await claim(other);
  assert.deepEqual((await read())[0].data, original, 'Row-level security hides other accounts and their edits');
  assert.equal((await db.query("select public.get_workspace_record('applications','a') as record")).rows[0].record.title, 'Original A', 'Single-record reads are account scoped');
  await save([{ key: 'dailyTasks', type: 'put', id: 'private-other', base: null, value: { id: 'private-other' } }]);
  await claim(owner);
  assert.equal((await read())[0].data.dailyTasks, undefined);
  await db.exec('reset role; set role anon');
  await assert.rejects(save([]), /permission denied/i);
  console.log('PASS page-storage SQL: no table split, RLS isolation, independent record edits, conflicts, atomic rollback, idempotent retries, ordering and small acknowledgements.');
} finally { await db.close(); }
