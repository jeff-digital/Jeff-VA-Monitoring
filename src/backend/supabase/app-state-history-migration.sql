-- Jeff VA / Client Compass: app-state recovery history
-- Run this once in Supabase Dashboard -> SQL Editor.
-- It does not alter or delete your current workspace. From this point forward,
-- the previous version is retained before every app_state update or deletion.

create table if not exists public.app_state_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  data jsonb not null,
  app_state_updated_at timestamptz not null,
  archived_at timestamptz not null default now()
);

create index if not exists app_state_history_user_archived_at_idx
  on public.app_state_history (user_id, archived_at desc);

alter table public.app_state_history enable row level security;
revoke all on public.app_state_history from public, anon, authenticated;
grant select on public.app_state_history to authenticated;

drop policy if exists "Users can read their own app state history" on public.app_state_history;
create policy "Users can read their own app state history"
  on public.app_state_history for select
  to authenticated
  using (auth.uid() = user_id);

create or replace function public.archive_app_state()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.app_state_history (user_id, data, app_state_updated_at)
  values (old.user_id, old.data, old.updated_at);

  -- Keep the most recent 60 recovery points per user to bound storage growth.
  delete from public.app_state_history
  where user_id = old.user_id
    and id in (
      select id
      from public.app_state_history
      where user_id = old.user_id
      order by archived_at desc, id desc
      offset 60
    );

  return old;
end;
$$;

drop trigger if exists archive_app_state_before_change on public.app_state;
create trigger archive_app_state_before_change
  before update or delete on public.app_state
  for each row execute function public.archive_app_state();

-- This function restores one of the caller's retained snapshots. Restoring also
-- archives the current version, so a restore can itself be undone.
create or replace function public.restore_app_state_snapshot(p_snapshot_id bigint)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  snapshot_data jsonb;
begin
  if auth.uid() is null then
    raise exception 'Sign in to restore workspace data.';
  end if;

  select history.data
  into snapshot_data
  from public.app_state_history as history
  where history.id = p_snapshot_id
    and history.user_id = auth.uid();

  if snapshot_data is null then
    return false;
  end if;

  insert into public.app_state (user_id, data, updated_at)
  values (auth.uid(), snapshot_data, now())
  on conflict (user_id) do update set
    data = excluded.data,
    updated_at = excluded.updated_at;

  return true;
end;
$$;

revoke all on function public.archive_app_state() from public, anon, authenticated;
revoke all on function public.restore_app_state_snapshot(bigint) from public, anon, authenticated;
grant execute on function public.restore_app_state_snapshot(bigint) to authenticated;

notify pgrst, 'reload schema';
